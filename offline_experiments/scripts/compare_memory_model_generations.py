def _fmt(value: Any) -> str:
    return "NA" if value is None else f"{float(value):.4f}"


def _print_summary(report: Mapping[str, Any]) -> None:
    print(
        "new states="
        + str(
            report["new_generalization_evidence"]["snapshot"][
                "state_counts"
            ]
        )
    )
    for cohort in ("old", "new"):
        print(cohort)
        for model_id in (MODEL_11D, MODEL_NATIVE, MODEL_PHYSICAL):
            if cohort == "old":
                metrics = report["old_evidence"][
                    "common_native_holdout"
                ]["models"][model_id]
            else:
                metrics = report["new_generalization_evidence"][
                    "models"
                ][model_id]["overall"]
            center = metrics["center_accuracy"][
                "absolute_percentage_error_percent"
            ]
            safety = metrics["safety"]
            print(
                f"  {model_id}: "
                f"MAPE={_fmt(center['mean'])}% "
                f"P90={_fmt(center['p90'])}% "
                f"false_safe={safety['false_safe_oom']}/"
                f"{safety['oom_rows']} "
                f"coverage={_fmt(safety['success_upper_coverage_percent'])}% "
                f"safe_recall={_fmt(safety['safe_success_admission_recall_percent'])}%"
            )
    print(
        "legacy_reproduction_max_relative_difference="
        + _fmt(
            report["legacy_11d_reconstruction"][
                "frozen_prediction_reproduction"
            ]["maximum_relative_difference"]
        )
    )
    print("report_sha256=" + str(report["report_sha256"]))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
    )
    args = parser.parse_args()
    report = build_report(args.output.resolve())
    _print_summary(report)


if __name__ == "__main__":
    main()
