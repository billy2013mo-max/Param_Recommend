def _metrics(
    records: Sequence[Mapping[str, Any]],
    predictions: Mapping[str, Mapping[str, Any]],
    *,
    p95_head: bool,
    include_details: bool,
) -> dict[str, Any]:
    ape: list[float] = []
    bias: list[float] = []
    absolute_gib: list[float] = []
    upper_coverage = 0
    success_rows = 0
    oom_rows = 0
    false_safe_oom = 0
    unavailable = 0
    actual_safe_success = 0
    admitted_safe_success = 0
    observed_over_safe_line_success = 0
    admitted_observed_over_safe_line_success = 0
    details: list[dict[str, Any]] = []
    by_config_success: dict[
        tuple[Any, ...], list[tuple[float, float]]
    ] = defaultdict(list)
    oom_configs: set[tuple[Any, ...]] = set()
    false_safe_oom_configs: set[tuple[Any, ...]] = set()
    observed_over_safe_line_configs: set[tuple[Any, ...]] = set()
    admitted_observed_over_safe_line_configs: set[
        tuple[Any, ...]
    ] = set()
    for record in records:
        observation_id = str(record["observation_id"])
        prediction = predictions[observation_id]
        resource_row = _record_resource_row(record)
        config_key = _config_key(resource_row)
        outcome = str(record["outcome"])
        detail = {
            "observation_id": observation_id,
            "job_id": record.get("job_id"),
            "outcome": outcome,
            "configuration": resource_row,
            "prediction_available": (
                prediction.get("available") is True
            ),
        }
        if prediction.get("available") is not True:
            unavailable += 1
            detail["issues"] = prediction.get("issues") or []
            if include_details:
                details.append(detail)
            continue
        center = float(prediction["reserved_center_bytes"])
        upper = float(prediction["decision_upper_bytes"])
        safe_limit = _safe_limit(record)
        if safe_limit is None:
            raise ValueError(f"{observation_id} has no safe limit")
        admitted = upper <= safe_limit
        detail.update(
            {
                "predicted_reserved_center_gib": center / GIB,
                "decision_upper_gib": upper / GIB,
                "safe_limit_gib": safe_limit / GIB,
                "predicted_admit": admitted,
                "decision_head": prediction["decision_head"],
            }
        )
        if outcome == "success":
            observed = _observed_reserved(record)
            if observed is None:
                unavailable += 1
                detail["issues"] = ["observed_reserved_missing"]
                if include_details:
                    details.append(detail)
                continue
            error = center - observed
            ape.append(abs(error) / observed)
            bias.append(error / observed)
            absolute_gib.append(abs(error) / GIB)
            success_rows += 1
            upper_coverage += int(observed <= upper)
            actual_safe = observed <= safe_limit
            if actual_safe:
                actual_safe_success += 1
                admitted_safe_success += int(admitted)
            else:
                observed_over_safe_line_success += 1
                observed_over_safe_line_configs.add(config_key)
                if admitted:
                    admitted_observed_over_safe_line_success += 1
                    admitted_observed_over_safe_line_configs.add(
                        config_key
                    )
            by_config_success[config_key].append((observed, center))
            detail.update(
                {
                    "observed_reserved_gib": observed / GIB,
                    "center_absolute_percentage_error": (
                        abs(error) / observed
                    ),
                    "upper_covers_observed": observed <= upper,
                    "actual_safe_success": actual_safe,
                }
            )
        elif outcome == "oom":
            oom_rows += 1
            oom_configs.add(config_key)
            false_safe_oom += int(admitted)
            if admitted:
                false_safe_oom_configs.add(config_key)
            detail["false_safe_oom"] = admitted
        if include_details:
            details.append(detail)
    config_ape: list[float] = []
    config_bias: list[float] = []
    for values in by_config_success.values():
        observed = statistics.median(value[0] for value in values)
        center = statistics.median(value[1] for value in values)
        config_ape.append(abs(center - observed) / observed)
        config_bias.append((center - observed) / observed)
    return {
        "center_accuracy": {
            "absolute_percentage_error_percent": _summary(
                [100.0 * value for value in ape]
            ),
            "signed_percentage_error_percent": _summary(
                [100.0 * value for value in bias]
            ),
            "absolute_error_gib": _summary(absolute_gib),
            "config_aggregated_absolute_percentage_error_percent": (
                _summary([100.0 * value for value in config_ape])
            ),
            "config_aggregated_signed_percentage_error_percent": (
                _summary([100.0 * value for value in config_bias])
            ),
        },
        "safety": {
            "decision_head": (
                "operational_p95"
                if p95_head
                else "point_estimate_no_calibrated_p95"
            ),
            "success_rows": success_rows,
            "success_upper_coverage": upper_coverage,
            "success_upper_coverage_percent": (
                100.0 * upper_coverage / success_rows
                if success_rows
                else None
            ),
            "coverage_is_formal_p95": p95_head,
            "oom_rows": oom_rows,
            "false_safe_oom": false_safe_oom,
            "false_safe_oom_rate_percent": (
                100.0 * false_safe_oom / oom_rows
                if oom_rows
                else None
            ),
            "unique_oom_configurations": len(oom_configs),
            "unique_false_safe_oom_configurations": len(
                false_safe_oom_configs
            ),
            "actual_safe_success_rows": actual_safe_success,
            "admitted_safe_success_rows": admitted_safe_success,
            "false_reject_safe_success": (
                actual_safe_success - admitted_safe_success
            ),
            "safe_success_admission_recall_percent": (
                100.0
                * admitted_safe_success
                / actual_safe_success
                if actual_safe_success
                else None
            ),
            "observed_over_safe_line_success_rows": (
                observed_over_safe_line_success
            ),
            "admitted_observed_over_safe_line_success_rows": (
                admitted_observed_over_safe_line_success
            ),
            "unique_observed_over_safe_line_success_configurations": (
                len(observed_over_safe_line_configs)
            ),
            "unique_admitted_observed_over_safe_line_success_configurations": (
                len(admitted_observed_over_safe_line_configs)
            ),
            "memory_admission_safety_failures": (
                false_safe_oom
                + admitted_observed_over_safe_line_success
            ),
            "memory_admission_safety_failure_definition": (
                "predicted admitted and either OOM or successful peak "
                "exceeded the 0.95-capacity line"
            ),
            "prediction_unavailable_rows": unavailable,
        },
        "details": details if include_details else None,
    }


def _subgroup_metrics(
    records: Sequence[Mapping[str, Any]],
    predictions: Mapping[str, Mapping[str, Any]],
    *,
    p95_head: bool,
) -> dict[str, Any]:
    groups: dict[tuple[str, str], list[Mapping[str, Any]]] = (
        defaultdict(list)
    )
    for record in records:
        groups[
            (
                str(record["scenario"]["model_id"]),
                str(record["selector"]["training_mode"]),
            )
        ].append(record)
    return {
        f"{model_id}/{training_mode}": _metrics(
            rows,
            predictions,
            p95_head=p95_head,
            include_details=False,
        )
        for (model_id, training_mode), rows in sorted(groups.items())
    }


def _frozen_11d_reproduction(
    *,
    beta: np.ndarray,
    models: Mapping[str, dict[str, Any]],
) -> dict[str, Any]:
    frozen = read_json(GENERALIZATION_MEMORY_LEDGER)
    differences: list[float] = []
    details: list[dict[str, Any]] = []
    for item in frozen["predictions"]:
        row = {
            "model_id": item["model_id"],
            "train_type": item["train_type"],
            "dataset_id": frozen["dataset_id"],
            "target_gbs": 64,
            "gpu_count": item["gpu_count"],
            "mbs": item["mbs"],
            "zero": item["zero"],
            "gc": item["gc"],
            "packing": False,
            "cutoff_len": frozen["cutoff_len"],
        }
        replayed = _predict_old_11d(row, beta, models)
        frozen_value = float(item["predicted_peak_reserved_bytes"])
        difference = abs(replayed - frozen_value) / frozen_value
        differences.append(difference)
        details.append(
            {
                "configuration": row,
                "frozen_bytes": frozen_value,
                "replayed_bytes": replayed,
                "relative_difference": difference,
            }
        )
    return {
        "rows": len(details),
        "maximum_relative_difference": max(differences),
        "mean_relative_difference": statistics.fmean(differences),
        "exact_within_1e_8_relative": max(differences) <= 1.0e-8,
        "details": details,
    }


