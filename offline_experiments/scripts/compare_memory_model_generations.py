#!/usr/bin/env python3
"""Replay the three H800 memory-model formulations on old and new evidence.

The three formulations are:

* the legacy 11-feature direct log-reserved regression used to freeze the
  2026-07-28 generalization predictions;
* the native augmented analytic/additive calibration;
* the physical-shares analytic-reference residual challenger.

The report deliberately separates center accuracy from admission safety.  The
legacy model has no calibrated P95 head, so its point estimate is also its
admission value.  The other two models use their frozen operational P95 heads.

No evaluated outcome is used to refit a frozen model.  For the legacy model,
the 617 pre-generalization completed configurations are reconstructed exactly.
On the old native holdout, its predictions are generated by leave-one-scenario-
out refits so that the held scenario is not present in its training rows.
"""

